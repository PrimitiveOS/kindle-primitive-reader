-- Run from the pinned Mac KOReader runtime with an authored EPUB, empty cache
-- directory and the Reader fixture Noto Sans Regular font.
require("setupkoenv")
G_defaults = require("luadefaults"):open()
local storage = require("datastorage")
G_reader_settings = require("luasettings"):open(storage:getDataDir() .. "/settings.reader.lua")
local device = require("device")
require("document/canvascontext"):init(device)
local cre = require("libs/libkoreader-cre")
local bb = require("ffi/blitbuffer")
local source, cache, font = assert(arg[1]), assert(arg[2]), assert(arg[3])
cre.initCache(cache, 32 * 1024 * 1024, true, 1)
cre.registerFont(font)

local width, height = 1264, 1606
local frame = bb.new(width, height, bb.TYPE_BB8)
local function state(size)
    local view = cre.newDocView(width, height, 1)
    view:setStyleSheet("./data/epub.css", "")
    view:setPageMargins(54, 54, 54, 54)
    view:setVisiblePageCount(1, false)
    view:setHeaderInfo(0)
    view:setFontFace("Noto Sans")
    view:setDefaultInterlineSpace(120)
    view:setIntProperty("crengine.cache.filesize.min", 0)
    view:setFontSize(size)
    assert(view:loadDocument(source, false))
    view:renderDocument()
    return view
end

local view = state(29)
assert(view:hasCacheFile())
assert(view:canBePartiallyRerendered())
local initial = view:getPages()
local hits = assert(view:findAllText("Beyond the shore", false, false, 4, true, 0, 255))
local focus = assert(hits[1])
local passage = view:getTextFromXPointers(focus.start, focus["end"])
assert(passage == "Beyond the shore")
view:gotoXPointer(focus.start)
view:drawCurrentPage(frame, false, false, false, false)

view:enablePartialRerendering(true)
assert(view:isPartialRerenderingEnabled())
view:setFontSize(48)
-- ReaderRolling:onUpdatePos forces the render decision before reading its hash.
view:getCurrentPos()
view:getDocumentRenderingHash(true)
assert(view:isRerenderingDelayed(false))
assert(view:getPartialRerenderingsCount() == 0)
view:drawCurrentPage(frame, false, false, false, false)
assert(view:getPartialRerenderingsCount() > 0)
assert(view:getTextFromXPointers(focus.start, focus["end"]) == passage)
view:gotoXPointer(focus.start)
assert(view:getCurrentPage() == view:getPageFromXPointer(focus.start))
local provisional = view:getPages()
assert(view:enablePartialRerendering(false))
view:renderDocument()
local completed = view:getPages()
assert(not view:isPartialRerenderingEnabled() and not view:isRerenderingDelayed(false))
assert(view:getTextFromXPointers(focus.start, focus["end"]) == passage)
view:close()

local fresh = state(29)
assert(not fresh:isPartialRerenderingEnabled())
fresh:gotoXPointer(focus.start)
fresh:setFontSize(48)
fresh:getCurrentPos()
assert(not fresh:isRerenderingDelayed(false) and fresh:getPartialRerenderingsCount() == 0)
assert(fresh:getPages() == completed and completed ~= initial)
assert(fresh:getTextFromXPointers(focus.start, focus["end"]) == passage)
print(string.format(
    "CREngine partial typography: baseline=%d, fragment-pass=%d, direct full=%d, source restored.",
    initial, provisional, completed))
fresh:close()
frame:free()
device:exit()
