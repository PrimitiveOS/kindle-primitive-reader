-- Run from the pinned KOReader build with its Lua source on LUA_PATH.
-- Pass an isolated scratch directory, the pinned KOReader checkout, a book and a font file.
local scratch, roots, book, font = assert(arg[1]), assert(arg[2]), assert(arg[3]), assert(arg[4])
os.setlocale("C", "numeric")
require("setupkoenv")
local cre = require("libs/libkoreader-cre")
local lfs = require("libs/libkoreader-lfs")
local cache = scratch .. "/facing-viewport-cache"
assert(lfs.symlinkattributes(scratch, "mode") == "directory" and lfs.mkdir(cache))
cre.initCache(cache, 0, true, 1)
cre.registerFont(font)
local file = assert(io.open(roots .. "/frontend/document/credocument.lua"))
local lua = file:read("*a")
file:close()
local stock_source = assert(lua:match("(function CreDocument:setVisiblePageCount%(new_count%).-\nend)"))
local ctx = { CreDocument = {}, logger = { dbg = function() end } }
setfenv(assert(loadstring(stock_source)), ctx)()
local doc = cre.newDocView(1264, 1680, 1)
doc:setStyleSheet("./data/epub.css", "")
doc:setFontSize(76)
doc:setFontFace("Noto Sans")
assert(doc:loadDocument(book, false))
local wrapper = { _document = doc }
local function assert_layout(label, width, height, xpointer)
    doc:setViewDimen(width, height)
    doc:renderDocument()
    assert(doc:getVisiblePageCount() == 2)
    assert(doc:isXPointerInDocument(xpointer))
    local page = doc:getPageFromXPointer(xpointer, true)
    local first = page % 2 == 0 and page - 1 or page
    doc:gotoPage(first, true)
    assert(doc:getCurrentPage(true) == first)
    print(label, width, height, page, doc:getPageOffsetX(first), doc:getPageOffsetX(first + 1))
end

doc:setVisiblePageCount(2, true)
assert(doc:getVisiblePageCount() == 1)
ctx.CreDocument.setVisiblePageCount(wrapper, 2)
assert(doc:getVisiblePageCount() == 2)
doc:renderDocument()
local anchor = doc:getPageXPointer(2, true)
assert(anchor and anchor ~= "")
assert_layout("portrait", 1264, 1680, anchor)
assert_layout("landscape", 1680, 1264, anchor)
doc:setViewMode(0)
assert(doc:getVisiblePageCount() == 1)
doc:setViewMode(1)
assert_layout("returned", 1264, 1680, anchor)
doc:close()
