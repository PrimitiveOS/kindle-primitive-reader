//! Caption placement changes a native table's reading geometry, not its source.
use super::{Cell, TableFlow, TableKey};
use crate::{
    Settings,
    book_style::{Style, flow::Display},
    publisher_padding::BoxArea,
    source::{Block, Source},
    table_borders::{Borders, Frame, Stroke},
    vertical_padding::Fill,
};
use std::{collections::HashMap, ops::Range};

#[derive(Clone, Copy)]
pub(crate) struct Placement {
    pub table: TableKey,
    pub element: usize,
    pub bottom: bool,
    pub first: bool,
    pub last: bool,
}

#[derive(Default)]
struct Run {
    grid: Vec<usize>,
    caption: Vec<usize>,
    owner: Option<usize>,
    ambiguous: bool,
}

#[derive(Default)]
pub(crate) struct Plan {
    order: Option<Vec<usize>>,
    placements: HashMap<usize, Placement>,
}

impl Plan {
    pub(crate) fn new(
        source: &Source,
        flow: &TableFlow<'_>,
        styles: &[Style],
        column_for: impl Fn(&Block) -> Option<Cell>,
        joined: &[Range<usize>],
    ) -> Self {
        let mut plan = Self::default();
        if flow.cells().is_empty()
            || !source.elements.iter().zip(styles).any(|(element, style)| {
                element.tag == "caption"
                    && style.display == Display::TableCaption
                    && !style.flow.suppressed
            })
        {
            return plan;
        }

        let mut tables = Vec::with_capacity(source.elements.len());
        let mut captions = Vec::with_capacity(source.elements.len());
        for (i, element) in source.elements.iter().enumerate() {
            let parent = element.parent;
            tables.push(if element.tag == "table" {
                Some(i)
            } else {
                parent.and_then(|p| tables[p])
            });
            captions.push(if element.tag == "table" {
                None
            } else if element.tag == "caption" {
                (styles[i].display == Display::TableCaption && !styles[i].flow.suppressed)
                    .then_some(i)
            } else {
                parent.and_then(|p| captions[p])
            });
        }
        let native: HashMap<_, _> = flow
            .cells()
            .iter()
            .filter(|(_, cell)| matches!(cell.table, TableKey::Native(_)))
            .filter_map(|(element, cell)| Some((tables[*element]?, cell.table)))
            .collect();
        let table_for_caption =
            |caption: usize| tables[caption].and_then(|i| native.get(&i).copied());
        let mut runs = HashMap::<TableKey, Run>::new();
        let mut owners = vec![None; source.blocks.len()];
        for (index, block) in source.blocks.iter().enumerate() {
            if styles[block.element].flow.suppressed {
                continue;
            }
            if let Some(cell) = column_for(block)
                && matches!(cell.table, TableKey::Native(_))
            {
                runs.entry(cell.table).or_default().grid.push(index);
                owners[index] = Some(cell.table);
                continue;
            }
            // A bare caption can sit inside an anonymous wrapper generated by
            // source extraction. Its text and images still name their owners.
            let caption = captions[block.element].or_else(|| {
                if !source.elements[block.element].anonymous {
                    return None;
                }
                let mut content = block
                    .styled_text
                    .iter()
                    .map(|run| run.element)
                    .chain(block.images.iter().map(|image| image.element));
                let owner = captions[content.next()?]?;
                content
                    .all(|element| captions[element] == Some(owner))
                    .then_some(owner)
            });
            if let Some(caption) = caption
                && let Some(table) = table_for_caption(caption)
            {
                let run = runs.entry(table).or_default();
                run.ambiguous |= run.owner.is_some_and(|owner| owner != caption);
                run.owner = Some(caption);
                run.caption.push(index);
                owners[index] = Some(table);
            }
        }

        for (table, run) in runs {
            if run.ambiguous || run.caption.is_empty() || run.grid.is_empty() {
                continue;
            }
            let first = run.caption[0].min(run.grid[0]);
            let last = (*run.caption.last().unwrap()).max(*run.grid.last().unwrap());
            if joined
                .iter()
                .any(|note| note.start <= last && first < note.end)
                || (first..=last).any(|i| {
                    owners[i] != Some(table) && !styles[source.blocks[i].element].flow.suppressed
                })
            {
                continue;
            }
            let element = run.owner.unwrap();
            let bottom = styles[element].caption_bottom;
            for &index in &run.caption {
                plan.placements.insert(
                    index,
                    Placement {
                        table,
                        element,
                        bottom,
                        first: run.caption.first() == Some(&index),
                        last: run.caption.last() == Some(&index),
                    },
                );
            }
            let order = plan
                .order
                .get_or_insert_with(|| (0..source.blocks.len()).collect());
            order[first..=last].sort_by_key(|index| {
                if plan.placements.contains_key(index) {
                    if bottom { 2 } else { 0 }
                } else {
                    1
                }
            });
        }
        plan
    }

    pub(crate) fn order(&self) -> Option<&[usize]> {
        self.order.as_deref()
    }

    pub(crate) fn placement(&self, source_index: usize) -> Option<Placement> {
        self.placements.get(&source_index).copied()
    }

    pub(crate) fn bands(&self) -> impl Iterator<Item = Placement> + '_ {
        self.placements
            .values()
            .copied()
            .filter(|placement| placement.first)
    }
}

pub(crate) fn source_index(order: Option<&[usize]>, slot: usize) -> usize {
    order.map_or(slot, |indices| indices[slot])
}

pub(crate) struct Decoration {
    columns: Range<u32>,
    strokes: [Stroke; 4],
    gray: Option<u8>,
    insets: [f32; 2],
    outer_stroke: f32,
}

impl Decoration {
    pub(crate) fn new(
        caption: Placement,
        style: &Style,
        boxes: Option<&[BoxArea]>,
        borders: Option<&Borders>,
        settings: Settings,
    ) -> Self {
        let (x, width) = boxes.map_or((0, settings.text_width()), |boxes| {
            let area = boxes[caption.element];
            (area.outer_x, area.outer_width)
        });
        let strokes = style
            .borders
            .as_ref()
            .map(|edges| edges.map(|edge| Stroke::read(edge, settings.font_size)))
            .unwrap_or_default();
        let insets = [0, 1].map(|side| {
            style.vertical_padding[side]
                .box_pixels(width, settings.font_size)
                .clamp(0.0, settings.text_height() as f32 / 2.0)
                + strokes[side * 2].width as f32
        });
        Self {
            columns: x..x + width,
            strokes: strokes.map(|stroke| {
                if style.flow.painted {
                    stroke
                } else {
                    Stroke {
                        gray: None,
                        ..stroke
                    }
                }
            }),
            gray: style.background.filter(|_| style.flow.painted),
            insets,
            outer_stroke: borders.map_or(0, |b| b.caption_stroke(caption.table, caption.bottom))
                as f32,
        }
    }

    pub(crate) fn outer(&self, caption: Placement, content: Range<f32>) -> Range<f32> {
        if caption.bottom {
            content.start..content.end + self.outer_stroke
        } else {
            content.start - self.outer_stroke..content.end
        }
    }

    pub(crate) fn leading(&self, caption: Placement) -> [f32; 2] {
        [
            if caption.bottom {
                0.0
            } else {
                self.outer_stroke
            },
            self.insets[0],
        ]
    }

    pub(crate) fn trailing(&self) -> f32 {
        self.insets[1]
    }

    pub(crate) fn paint(
        &self,
        caption: Placement,
        content: Range<f32>,
        frames: &mut Vec<Frame>,
        fills: &mut Vec<Fill>,
    ) {
        if let Some(gray) = self.gray {
            fills.push(Fill::rectangle(
                caption.element,
                self.columns.clone(),
                content.start,
                content.end,
                gray,
            ));
        }
        Frame::push(
            frames,
            self.columns.start,
            self.columns.end - self.columns.start,
            content.start,
            content.end,
            self.strokes,
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Book, book_style::BookStyle};

    #[test]
    fn table_caption_schedule_skips_only_joined_notes_that_overlap_the_grid() {
        let fixture = crate::test_fixture("table-captions.xhtml");
        let source = Source::parse(&std::fs::read_to_string(&fixture).unwrap()).unwrap();
        let mut book = Book::open(&fixture).unwrap();
        let spine = book.chapters[0].href.clone();
        let styles =
            BookStyle::load_for_flow(&mut book, &spine, &source, true, &Default::default())
                .unwrap()
                .compute(&source.elements);
        let flow = TableFlow::new(&source, &styles).unwrap();
        let block = |phrase: &str| {
            source
                .blocks
                .iter()
                .position(|block| block.text.contains(phrase))
                .unwrap()
        };
        let late = block("Late caption");
        let north = block("North berth");
        let south = block("South berth");
        let author = block("Author caption");
        let outer = block("Quay log.");
        let plan = |joined: &[Range<usize>]| {
            Plan::new(
                &source,
                &flow,
                &styles,
                |block| flow.block_cell(block),
                joined,
            )
        };
        let ordinary = plan(&[outer..outer + 1]);
        let index = |plan: &Plan, index| {
            plan.order()
                .unwrap()
                .iter()
                .position(|&block| block == index)
                .unwrap()
        };
        assert!(index(&ordinary, late) < index(&ordinary, north));
        let settings = crate::PublisherRenderMode::Book.apply(Settings::default());
        let margins =
            crate::block_margins::before_blocks(&source, &styles, None, settings, ordinary.order())
                .unwrap();
        for phrase in ["East berth", "South berth", "Override caption"] {
            assert_eq!(
                margins[index(&ordinary, block(phrase))].before,
                8.,
                "{phrase}"
            );
        }
        let interrupted = plan(&[north..north + 1]);
        assert!(index(&interrupted, late) > index(&interrupted, north));
        assert!(index(&interrupted, south) < index(&interrupted, author));
    }
}
